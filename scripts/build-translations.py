#!/usr/bin/env python3
"""Generate the runtime catalog from translator-friendly PO source.
Requires gettext's msgfmt. --check detects stale generated files, not missing
translations: untranslated/fuzzy entries fall back to English at runtime.
"""
import argparse
import gettext
import io
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
compiled = subprocess.run(['msgfmt', '--check', '-o', '-', str(root / 'l10n/zh_CN.po')],
                          check=True, stdout=subprocess.PIPE).stdout
catalog = gettext.GNUTranslations(io.BytesIO(compiled))._catalog
quote = lambda value: json.dumps(value, ensure_ascii=False)
lines = ['-- Generated by scripts/build-translations.py; edit l10n/zh_CN.po instead.', 'return {']
for key, value in sorted(catalog.items()):
    if key:
        if not isinstance(key, str):
            raise ValueError('Plural messages need runtime plural support before being added.')
        lines.append(f'    [{quote(key)}] = {quote(value)},')
lines.append('}')
source = '\n'.join(lines) + '\n'
target = root / 'neodb_zh_cn.lua'
if args.check:
    if target.read_text() != source:
        raise SystemExit('Run python3 scripts/build-translations.py to refresh the runtime catalog.')
else:
    target.write_text(source)
